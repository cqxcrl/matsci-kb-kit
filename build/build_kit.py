#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""build_kit.py — matsci-kb-kit 生成器（单入口）。

把源知识库（真源）的 `tools/` 按 include 白名单过滤、按 scrub 表去个人化后，
生成到本 kit 仓库的 `tools/`。kit 是**派生数据**，真源永远是源库。

三条架构不变量（让「不破坏源库」机械化）：
  1. build 只写 --out；若 --out 落在 --src（源库）内则直接 abort（硬门禁）。
  2. fail-closed 泄漏扫描：生成后扫输出树，命中 leak_denylist 即构建失败。
  3. 漂移可见：scrub 规则若在源文件中找不到目标（源码已变），打印告警；
     若因此残留泄漏，由第 2 条兜底为构建失败。

用法：
  python build/build_kit.py                     # 用默认源库与默认输出（本仓库根）
  python build/build_kit.py --src <库根> --out <kit根>
  python build/build_kit.py --check             # 只跑泄漏扫描（不生成）
"""
import argparse
import io
import os
import re
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
KIT_ROOT = os.path.dirname(HERE)               # build/ 的父目录 = kit 仓库根
RULES = os.path.join(HERE, "rules")

# 源库默认：显式允许（本生成器是手写件，不进泄漏扫描）。
DEFAULT_SRC = os.environ.get("MATSCI_KB_SRC") or r"E:\Matsci Knowledge Base"

BANNER = "# ── GENERATED by matsci-kb-kit build/build_kit.py — DO NOT EDIT (真源见 kit.yaml) ──\n"

# 编码方法论、需随包发布的少数质量工具（CLAUDE.md 点名了 qc_evidence_base）。
# 必须与源库同为**平铺**布局：它们用 sys.path.insert(0, dirname(__file__)) 找 kb_lib，
# 放进子目录会 ImportError。
EXTRAS = {  # src/tools 文件名 → kit 内相对路径
    "qc_evidence_base.py": "tools/qc_evidence_base.py",
    "qc_schema_check.py":  "tools/qc_schema_check.py",
    "qc_base_check.py":    "tools/qc_base_check.py",
}

# 生成物中需被泄漏扫描覆盖的相对路径（相对 kit 根）。
SCAN_TARGETS = ["tools", "docs", "skills", "scaffold", "CLAUDE.md", "kit.yaml"]


def _read(path):
    with open(path, "r", encoding="utf-8", newline="") as f:
        return f.read()


def _write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def load_lines(name):
    p = os.path.join(RULES, name)
    out = []
    for ln in _read(p).splitlines():
        ln = ln.strip()
        if ln and not ln.startswith("#"):
            out.append(ln)
    return out


def load_scrub():
    """返回 {filename: [(find, replace), ...]}，保持列表顺序。"""
    import yaml
    data = yaml.safe_load(_read(os.path.join(RULES, "scrub.yaml"))) or {}
    by_file = {}
    for r in data.get("rules", []):
        by_file.setdefault(r["file"], []).append((r["find"], r["replace"]))
    return by_file


def apply_scrub(text, filename, scrub, warn):
    for find, repl in scrub.get(filename, []):
        if find not in text:
            warn.append(f"scrub 未命中 {filename}: {find[:60]!r}（源文件可能已变）")
            continue
        text = text.replace(find, repl)
    return text


def add_banner(text):
    """在 shebang 之后（若有）插入勿编辑横幅，保持 shebang 语义。"""
    if text.startswith("#!"):
        nl = text.find("\n")
        return text[:nl + 1] + BANNER + text[nl + 1:]
    return BANNER + text


def generate_tools(src, out, scrub, warn, log):
    inc = load_lines("include.txt")
    n = 0
    for name in inc:
        s = os.path.join(src, "tools", name)
        if not os.path.isfile(s):
            warn.append(f"include 列出的文件不存在：tools/{name}")
            continue
        text = apply_scrub(_read(s), name, scrub, warn)
        _write(os.path.join(out, "tools", name), add_banner(text))
        n += 1
    for name, rel in EXTRAS.items():
        s = os.path.join(src, "tools", name)
        if not os.path.isfile(s):
            warn.append(f"extras 列出的文件不存在：tools/{name}")
            continue
        text = apply_scrub(_read(s), name, scrub, warn)
        _write(os.path.join(out, rel), add_banner(text))
        n += 1
    log(f"[tools]    生成 {n} 个文件")
    return n


def scan_leaks(root):
    deny = load_lines("leak_denylist.txt")
    pats = [(p, re.compile(p)) for p in deny]
    hits = []
    for target in SCAN_TARGETS:
        t = os.path.join(root, target)
        if os.path.isfile(t):
            files = [t]
        elif os.path.isdir(t):
            files = [os.path.join(dp, f) for dp, _, fs in os.walk(t) for f in fs]
        else:
            continue
        for fp in files:
            try:
                text = _read(fp)
            except Exception:                                # noqa: BLE001
                continue
            for i, ln in enumerate(text.splitlines(), 1):
                for pat, rx in pats:
                    if rx.search(ln):
                        hits.append((os.path.relpath(fp, root).replace("\\", "/"),
                                     i, pat, ln.strip()[:100]))
    return hits


def transform_claude(text, warn):
    """对 CLAUDE.md 施加 drop_sections 块级变换 + 换行/指针归一化。"""
    import yaml
    data = yaml.safe_load(_read(os.path.join(RULES, "drop_sections.yaml"))) or {}
    for r in data.get("rules", []):
        find, repl = r["find"], r["replace"]
        if find not in text:
            warn.append(f"CLAUDE.md 变换未命中: {find[:60]!r}（真源已漂移）")
            continue
        text = text.replace(find, repl)
    # 归一化：指向未随包发布的文档（_MAINTENANCE/_INCIDENTS）的指针 → 删除该行
    lines = []
    for ln in text.split("\n"):
        if re.search(r"_MAINTENANCE\.md|_INCIDENTS\.md", ln):
            continue
        lines.append(ln)
    text = "\n".join(lines)
    # 归一化：源库称「本库」→「本工具链」（kit 语境）
    text = text.replace("本库", "本工具链")
    # 归一化：工程专属路径名（通用化）
    text = text.replace("AI-for-Materials-Review", "综述工程")
    # 折叠 3+ 连续空行
    text = re.sub(r"\n{4,}", "\n\n\n", text)
    return text


# 随包发布的技能（源 .dsh/skills/ 下的目录名）→ kit 内相对路径。
# 排除工程专属（kb-qc-loop/kb-review-cycle/kb-ingest-batch）与陈旧 batch-ops。
SKILLS = ["lit-pipeline", "lit-watch", "kb-query", "kb-lint", "kb-onboard"]
SKILL_SCRUB = [
    (r"E:\\Matsci Knowledge Base", "<你的库根>"),
    (r"E:/Matsci Knowledge Base", "<你的库根>"),
    (r"E:\\\.claude", "<你的 .claude>"),
    (r"C:\\Users\\asus\\\.claude", "<你的 .claude>"),
    (r"E:\\claude-results", "<库内运行产物目录>"),
    (r"E:/claude-results", "<库内运行产物目录>"),
    (r"Matsci Knowledge Base", "本工具链"),
    (r"AI-for-Materials-Review", "综述工程"),
    (r"镍铁催化剂机理探究", "你的文献目录"),
    (r"Chem&Mater", "你的文献目录"),
    (r"E:[\\/][^\s'\"]*", "<库外路径>"),        # 兜底：残留的 E:\ 或 E:/ 路径
]


def generate_carriers(src, out, warn, log):
    """生成 CLAUDE.md + docs/METHODOLOGY.md + skills/。"""
    # CLAUDE.md
    claude_src = os.path.join(src, "CLAUDE.md")
    if os.path.isfile(claude_src):
        t = transform_claude(_read(claude_src), warn)
        _write(os.path.join(out, "CLAUDE.md"), t)
        _write(os.path.join(out, "docs", "METHODOLOGY.md"), t)
        log("[carriers] 生成 CLAUDE.md + docs/METHODOLOGY.md")

    # skills
    n = 0
    for name in SKILLS:
        sk = os.path.join(src, ".dsh", "skills", name)
        if not os.path.isdir(sk):
            warn.append(f"技能目录不存在：.dsh/skills/{name}")
            continue
        for dp, _, fs in os.walk(sk):
            rel = os.path.relpath(dp, sk)
            for f in fs:
                text = _read(os.path.join(dp, f))
                for pat, repl in SKILL_SCRUB:
                    text = re.sub(pat, lambda m, r=repl: r, text)
                dst = os.path.join(out, "skills", name,
                                   *([] if rel == "." else rel.split(os.sep)), f)
                _write(dst, text)
                n += 1
    log(f"[carriers] 生成 {n} 个技能文件 ({', '.join(SKILLS)})")

    # docs/TOOLS.md（由 tools/_README.md 变换）
    rd = os.path.join(src, "tools", "_README.md")
    if os.path.isfile(rd):
        t = _read(rd)
        t = re.sub(r"^.*(?:Matsci Knowledge Base|Battery Knowledge Base|原名).*$",
                   "", t, flags=re.M)          # 删除更名史行
        keep = []
        skip_ingest = False
        for ln in t.split("\n"):
            if re.search(r"_INCIDENTS\.md|_MAINTENANCE\.md|_LIT-WATCH-NEXT\.md", ln):
                continue
            if re.match(r"^## Ingest 工具链", ln):
                skip_ingest = True; continue
            if skip_ingest and re.match(r"^## ", ln):
                skip_ingest = False
            if skip_ingest:
                continue
            keep.append(ln)
        t = "\n".join(keep)
        t = t.replace("Matsci Knowledge Base", "本工具链").replace("本库", "本工具链")
        t = re.sub(r"E:[\\/][^\s`'\"]*", "<库外路径>", t)
        t = re.sub(r"AI-for-Materials-Review", "综述工程", t)
        t = re.sub(r"\n{4,}", "\n\n\n", t)
        _write(os.path.join(out, "docs", "TOOLS.md"), t)
        log("[carriers] 生成 docs/TOOLS.md")
    return n


def write_kit_yaml(out, src, inc_total):
    import subprocess
    import hashlib
    def sha(p):
        h = hashlib.sha256()
        with open(p, "rb") as f:
            for b in iter(lambda: f.read(65536), b""):
                h.update(b)
        return h.hexdigest()
    try:
        commit = subprocess.run(["git", "-C", src, "rev-parse", "HEAD"],
                                capture_output=True, text=True,
                                timeout=10).stdout.strip() or "unknown"
    except Exception:                                        # noqa: BLE001
        commit = "unknown"
    files = {}
    tools_dir = os.path.join(out, "tools")
    for dp, dnames, fs in os.walk(tools_dir):
        dnames[:] = [d for d in dnames if d != "__pycache__"]
        for f in fs:
            if f.endswith((".pyc", ".pyo")):
                continue
            fp = os.path.join(dp, f)
            files[os.path.relpath(fp, out).replace("\\", "/")] = sha(fp)
    import yaml
    doc = {
        "_generated_by": "build/build_kit.py",
        "_note": "本 kit 是由源知识库过滤+去个人化生成的派生数据；真源不在此仓库。",
        "source_commit": commit,
        "built_at": time.strftime("%Y-%m-%dT%H:%M:%S"),
        "note": "生成物请勿手改；改真源后重跑 build_kit.py。",
        "tools": sorted(files.keys()),
        "tool_sha256": files,
    }
    _write(os.path.join(out, "kit.yaml"),
           yaml.safe_dump(doc, allow_unicode=True, sort_keys=False))
    return commit


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default=DEFAULT_SRC, help="源知识库根（真源）")
    ap.add_argument("--out", default=KIT_ROOT, help="kit 仓库根（输出）")
    ap.add_argument("--check", action="store_true", help="只跑泄漏扫描，不生成")
    ap.add_argument("--strict", action="store_true", help="scrub 未命中即失败")
    args = ap.parse_args()

    src = os.path.abspath(args.src)
    out = os.path.abspath(args.out)
    warn = []

    def log(m):
        print(m, flush=True)

    # 不变量 1：输出不得落在源库内
    if os.path.commonpath([src, out]) == src:
        print(f"[ABORT] --out({out}) 落在 --src({src}) 内；拒绝生成（不变量 1）")
        return 2

    if not args.check:
        if not os.path.isfile(os.path.join(src, "tools", "kb_lib.py")):
            print(f"[ABORT] 源库不像知识库（缺 tools/kb_lib.py）：{src}")
            return 2
        log(f"源库: {src}")
        log(f"输出: {out}")
        scrub = load_scrub()
        generate_tools(src, out, scrub, warn, log)
        generate_carriers(src, out, warn, log)
        commit = write_kit_yaml(out, src, 0)
        log(f"[kit.yaml] source_commit={commit}")

    # 不变量 2：fail-closed 泄漏扫描
    hits = scan_leaks(out)
    log("")
    if hits:
        log(f"=== 泄漏扫描：{len(hits)} 处命中 → 构建失败 ===")
        for f, i, pat, txt in hits:
            log(f"  {f}:{i}  [{pat}]  {txt}")
    else:
        log("=== 泄漏扫描：0 命中 ===")

    if warn:
        log(f"\n告警 {len(warn)} 条：")
        for w in warn:
            log(f"  ! {w}")

    if hits or (args.strict and warn):
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
