#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""build_kit.py — matsci-kb-kit 生成器（单入口）。

把源知识库（真源）的 `tools/` 按 include 白名单过滤、按 scrub 表去个人化后，
生成到本 kit 仓库的 `tools/`。kit 是**派生数据**，真源永远是源库。

三条架构不变量（让「不破坏源库」机械化）：
  1. build 只写 --out；若 --out 落在 --src（源库）内则直接 abort（硬门禁）。
  2. fail-closed 泄漏扫描：生成后扫输出树，命中 leak_denylist 即构建失败。
  3. 漂移可见：scrub 规则若在源文件中找不到目标（源码已变），打印告警；
     若因此残留泄漏，由第 2 条兜底为构建失败。

用法：
  python build/build_kit.py --src <库根> --out <kit根>
  python build/build_kit.py --check             # 只跑泄漏扫描（不生成）
--src 缺省读环境变量 MATSCI_KB_SRC；本脚本不内置任何本机路径。

🔴 关于 build/rules/private/
  去个人化规则**本身就是敏感数据**：要替换掉源库的专名，就得先把专名写在规则里。
  而 build/ 既进 git 又进 npm 包，还刻意不在泄漏扫描范围内（规则必须以字面量保存专名）。
  两者相加 ⇒ 规则若直接发布，生成器就会把它本该抹掉的东西原样公开：本机用户名、
  库根路径、文献管理器数据目录、个人文献文件夹名，以及整份研究方向清单。
  所以含专名的五个规则文件全部放在 **gitignored** 的 `build/rules/private/` 下，
  仓库里只留 `build/rules/examples/` 的假值模板。分工与起步方法见 build/rules/README.md。
  私有规则缺失时本脚本**不静默降级**：生成会中止（退出码 2）；--check 仍可跑，
  但只按公开那份通用 denylist 扫描，并把降级说出口。
"""
import argparse
import io
import os
import re
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
KIT_ROOT = os.path.dirname(HERE)               # build/ 的父目录 = kit 仓库根
RULES = os.path.join(HERE, "rules")            # 公开：include/exclude/通用 denylist/examples
PRIVATE = os.path.join(RULES, "private")       # gitignored：一切含专名的规则

# 私有规则清单：生成时缺任何一个都不能安全产出。
PRIVATE_FILES = ["scrub.yaml", "global_scrub.yaml", "drop_sections.yaml",
                 "leak_denylist.txt", "skill_scrub.yaml"]

BANNER = "# ── GENERATED by matsci-kb-kit build/build_kit.py — DO NOT EDIT (真源见 kit.yaml) ──\n"

# 编码方法论、需随包发布的少数质量工具（CLAUDE.md 点名了 qc_evidence_base）。
# 必须与源库同为**平铺**布局：它们用 sys.path.insert(0, dirname(__file__)) 找 kb_lib，
# 放进子目录会 ImportError。
EXTRAS = {  # src/tools 文件名 → kit 内相对路径
    "qc_evidence_base.py": "tools/qc_evidence_base.py",
    "qc_schema_check.py":  "tools/qc_schema_check.py",
    "qc_base_check.py":    "tools/qc_base_check.py",
}

# 生成物中需被泄漏扫描覆盖的相对路径（相对 kit 根）。
# 手写件（README / bin / scripts / mcp / 各 docs）同样在扫描范围内——它们不经 scrub，
# 更容易把源库专名带进来。
# 🔴 `build/` 刻意**不扫**：private/ 下的规则必须以字面量保存这些专名，否则无从替换。
#    代价是 build/ 不能公开专名 —— 所以 private/ 整个目录 gitignored（见模块 docstring）。
SCAN_TARGETS = ["tools", "docs", "skills", "scaffold", "mcp", "bin", "scripts",
                "CLAUDE.md", "kit.yaml", "README.md", "NOTICE.md", "index.js",
                "package.json", "requirements.txt", "requirements-optional.txt"]


def _read(path):
    with open(path, "r", encoding="utf-8", newline="") as f:
        return f.read()


def _write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def private_paths():
    """返回缺失的私有规则文件（相对 build/ 的 POSIX 路径）。"""
    return [f"rules/private/{n}" for n in PRIVATE_FILES
            if not os.path.isfile(os.path.join(PRIVATE, n))]


def load_lines(name, where=RULES):
    p = os.path.join(where, name)
    out = []
    for ln in _read(p).splitlines():
        ln = ln.strip()
        if ln and not ln.startswith("#"):
            out.append(ln)
    return out


def load_scrub():
    """返回 {filename: [(find, replace), ...]}，保持列表顺序。"""
    import yaml
    data = yaml.safe_load(_read(os.path.join(PRIVATE, "scrub.yaml"))) or {}
    by_file = {}
    for r in data.get("rules", []):
        by_file.setdefault(r["file"], []).append((r["find"], r["replace"]))
    return by_file


def load_global_scrub():
    """全局专名替换表 [(find, replace), ...]，保持列表顺序（长/具体在前）。

    与 load_scrub 的分工：这里是**纯专名 → 占位符**，对每个生成物都跑一遍，
    未命中不告警（不是每个文件都含每个专名）；漏网由 leak_denylist 兜底为构建失败。
    """
    import yaml
    data = yaml.safe_load(_read(os.path.join(PRIVATE, "global_scrub.yaml"))) or {}
    return [(r["find"], r["replace"]) for r in data.get("rules", [])]


def load_skill_scrub():
    """技能文件的正则替换表 [(pattern, replacement), ...]。

    技能是**人写的散文**，同一个专名会以多种形态出现（带盘符的路径、裸库名、
    旧库名…），字面量替换覆盖不住，所以这一层用正则。放在数据文件而不是代码里，
    是为了让专名不出现在受版本控制的 .py 中。
    """
    import yaml
    data = yaml.safe_load(_read(os.path.join(PRIVATE, "skill_scrub.yaml"))) or {}
    return [(r["pattern"], r["replace"]) for r in data.get("rules", [])]


def load_drop_sections():
    """CLAUDE.md / _README.md 的块级删除表：{rules, drop_headings, drop_lines}。

    这三类都是「整段/整行删掉」而非替换，且规则里必然出现源库专名（否则无从定位），
    所以同样归 private/。
      · rules         —— 字面量 find/replace（成段改写，未命中告警）
      · drop_headings —— 按 Markdown 标题删到下一个同级标题（活台账用这个，不漂移）
      · drop_lines    —— 按正则逐行删（更名史这类一句话噪声）
    """
    import yaml
    return yaml.safe_load(_read(os.path.join(PRIVATE, "drop_sections.yaml"))) or {}


def apply_global_scrub(text, pairs, counter):
    for find, repl in pairs:
        n = text.count(find)
        if n:
            counter[find] = counter.get(find, 0) + n
            text = text.replace(find, repl)
    return text


def apply_scrub(text, filename, scrub, warn):
    for find, repl in scrub.get(filename, []):
        if find not in text:
            warn.append(f"scrub 未命中 {filename}: {find[:60]!r}（源文件可能已变）")
            continue
        text = text.replace(find, repl)
    return text


def add_banner(text):
    """在 shebang 之后（若有）插入勿编辑横幅，保持 shebang 语义。"""
    if text.startswith("#!"):
        nl = text.find("\n")
        return text[:nl + 1] + BANNER + text[nl + 1:]
    return BANNER + text


def generate_tools(src, out, scrub, gscrub, gcount, warn, log):
    inc = load_lines("include.txt")
    n = 0
    for name in inc:
        s = os.path.join(src, "tools", name)
        if not os.path.isfile(s):
            warn.append(f"include 列出的文件不存在：tools/{name}")
            continue
        text = apply_global_scrub(apply_scrub(_read(s), name, scrub, warn),
                                  gscrub, gcount)
        _write(os.path.join(out, "tools", name), add_banner(text))
        n += 1
    for name, rel in EXTRAS.items():
        s = os.path.join(src, "tools", name)
        if not os.path.isfile(s):
            warn.append(f"extras 列出的文件不存在：tools/{name}")
            continue
        text = apply_global_scrub(apply_scrub(_read(s), name, scrub, warn),
                                  gscrub, gcount)
        _write(os.path.join(out, rel), add_banner(text))
        n += 1
    log(f"[tools]    生成 {n} 个文件")
    return n


def scan_leaks(root):
    """fail-closed 泄漏扫描：公开通用规则 + 私有专名规则，两份都跑。

    为什么拆两份：规则里必然出现「要拦的东西长什么样」，而专名规则因此**本身就是隐私**。
      · build/rules/leak_denylist.txt          —— 通用（家目录/用户名形态），随仓库发布，
                                                  CI 也靠它兜底；不含任何真实专名。
      · build/rules/private/leak_denylist.txt  —— 源库专名清单，gitignored，只在本地存在。
    私有那份缺失时只告警不崩：否则 clone 下来的仓库连 --check 都跑不了。
    """
    deny = load_lines("leak_denylist.txt")
    priv = os.path.join(PRIVATE, "leak_denylist.txt")
    if os.path.isfile(priv):
        deny = deny + load_lines("leak_denylist.txt", PRIVATE)
    pats = [(p, re.compile(p)) for p in deny]
    hits = []
    for target in SCAN_TARGETS:
        t = os.path.join(root, target)
        if os.path.isfile(t):
            files = [t]
        elif os.path.isdir(t):
            files = [os.path.join(dp, f) for dp, _, fs in os.walk(t) for f in fs]
        else:
            continue
        for fp in files:
            try:
                text = _read(fp)
            except Exception:                                # noqa: BLE001
                continue
            for i, ln in enumerate(text.splitlines(), 1):
                for pat, rx in pats:
                    if rx.search(ln):
                        hits.append((os.path.relpath(fp, root).replace("\\", "/"),
                                     i, pat, ln.strip()[:100]))
    return hits


def drop_heading_sections(text, specs, warn):
    """按标题整段删除（到下一个同级或更高级标题为止），可选插入替代文本。

    为什么不用字面量 find/replace：这类段落是源库的**活台账**（诊断边界、
    已知欠账），几乎每轮都在改；字面量规则会天天漂移告警，最后被无视。
    按标题删则只要标题不动就稳。
    """
    for spec in specs:
        head = spec["heading"]
        level = len(head) - len(head.lstrip("#"))
        lines = text.split("\n")
        try:
            start = lines.index(head)
        except ValueError:
            warn.append(f"CLAUDE.md 标题未命中: {head!r}（真源已漂移）")
            continue
        end = len(lines)
        for i in range(start + 1, len(lines)):
            ln = lines[i]
            if ln.startswith("#") and (len(ln) - len(ln.lstrip("#"))) <= level:
                end = i
                break
        repl = spec.get("replace", "")
        lines[start:end] = repl.split("\n") if repl else []
        text = "\n".join(lines)
    return text


def transform_claude(text, drops, warn, gscrub, gcount):
    """对 CLAUDE.md 施加 drop_sections 块级变换 + 全局专名替换 + 换行/指针归一化。"""
    for r in drops.get("rules", []):
        find, repl = r["find"], r["replace"]
        if find not in text:
            warn.append(f"CLAUDE.md 变换未命中: {find[:60]!r}（真源已漂移）")
            continue
        text = text.replace(find, repl)
    text = drop_heading_sections(text, drops.get("drop_headings", []), warn)
    # 归一化：指向未随包发布的文档（_MAINTENANCE/_INCIDENTS）的指针 → 删除该行
    lines = []
    for ln in text.split("\n"):
        if re.search(r"_MAINTENANCE\.md|_INCIDENTS\.md", ln):
            continue
        lines.append(ln)
    text = "\n".join(lines)
    # 归一化：源库称「本库」→「本工具链」（kit 语境）
    text = text.replace("本库", "本工具链")
    # 全局专名替换（放最后：上面几条是更具体的成段改写，优先）
    text = apply_global_scrub(text, gscrub, gcount)
    # 折叠 3+ 连续空行
    text = re.sub(r"\n{4,}", "\n\n\n", text)
    return text


# 随包发布的技能（源 .dsh/skills/ 下的目录名）→ kit 内相对路径。
# 排除工程专属（kb-qc-loop/kb-review-cycle/kb-ingest-batch/sci-assistant）与陈旧 batch-ops。
SKILLS = ["lit-pipeline", "lit-watch", "lit-browser-fetch", "kb-query", "kb-lint", "kb-onboard"]


def generate_carriers(src, out, gscrub, gcount, sscrub, drops, warn, log):
    """生成 CLAUDE.md + docs/METHODOLOGY.md + docs/TOOLS.md + skills/。"""
    # CLAUDE.md
    claude_src = os.path.join(src, "CLAUDE.md")
    if os.path.isfile(claude_src):
        t = transform_claude(_read(claude_src), drops, warn, gscrub, gcount)
        _write(os.path.join(out, "CLAUDE.md"), t)
        _write(os.path.join(out, "docs", "METHODOLOGY.md"), t)
        log("[carriers] 生成 CLAUDE.md + docs/METHODOLOGY.md")

    # skills
    n = 0
    for name in SKILLS:
        sk = os.path.join(src, ".dsh", "skills", name)
        if not os.path.isdir(sk):
            warn.append(f"技能目录不存在：.dsh/skills/{name}")
            continue
        for dp, _, fs in os.walk(sk):
            rel = os.path.relpath(dp, sk)
            for f in fs:
                text = _read(os.path.join(dp, f))
                for pat, repl in sscrub:
                    text = re.sub(pat, lambda m, r=repl: r, text)
                text = apply_global_scrub(text, gscrub, gcount)
                dst = os.path.join(out, "skills", name,
                                   *([] if rel == "." else rel.split(os.sep)), f)
                _write(dst, text)
                n += 1
    log(f"[carriers] 生成 {n} 个技能文件 ({', '.join(SKILLS)})")

    # docs/TOOLS.md（由 tools/_README.md 变换）
    rd = os.path.join(src, "tools", "_README.md")
    if os.path.isfile(rd):
        t = _read(rd)
        # 更名史这类含专名的单行噪声：正则来自 private/drop_sections.yaml: drop_lines
        for spec in drops.get("drop_lines", []):
            t, n_drop = re.subn(spec["pattern"], "", t, flags=re.M)
            if not n_drop:
                warn.append(f"TOOLS.md drop_lines 未命中: {spec['pattern'][:60]!r}（真源已漂移）")
        keep = []
        skip_ingest = False
        for ln in t.split("\n"):
            if re.search(r"_INCIDENTS\.md|_MAINTENANCE\.md|_LIT-WATCH-NEXT\.md", ln):
                continue
            if re.match(r"^## Ingest 工具链", ln):
                skip_ingest = True; continue
            if skip_ingest and re.match(r"^## ", ln):
                skip_ingest = False
            if skip_ingest:
                continue
            keep.append(ln)
        t = "\n".join(keep)
        t = t.replace("本库", "本工具链")
        t = re.sub(r"[A-Za-z]:[\\/][^\s`'\"]*", "<库外路径>", t)
        t = apply_global_scrub(t, gscrub, gcount)
        t = re.sub(r"\n{4,}", "\n\n\n", t)
        _write(os.path.join(out, "docs", "TOOLS.md"), t)
        log("[carriers] 生成 docs/TOOLS.md")
    return n


def write_kit_yaml(out, src, inc_total):
    import subprocess
    import hashlib
    def sha(p):
        h = hashlib.sha256()
        with open(p, "rb") as f:
            for b in iter(lambda: f.read(65536), b""):
                h.update(b)
        return h.hexdigest()
    try:
        commit = subprocess.run(["git", "-C", src, "rev-parse", "HEAD"],
                                capture_output=True, text=True,
                                timeout=10).stdout.strip() or "unknown"
    except Exception:                                        # noqa: BLE001
        commit = "unknown"
    # 源库工作区若有未提交改动，光记 commit 就是**假溯源**：照着那个 commit 拉源码
    # 重建，得到的不是这个 kit。故把脏文件清单一并记下（只记 tools/ 下的，
    # 那是唯一会进 kit 的部分；wiki/raw 的改动与生成物无关，记了只是噪声）。
    dirty = []
    try:
        st = subprocess.run(["git", "-C", src, "status", "--porcelain", "--", "tools"],
                            capture_output=True, text=True, timeout=20).stdout
        dirty = sorted(ln[3:].strip() for ln in st.splitlines() if ln.strip())
    except Exception:                                        # noqa: BLE001
        pass
    files = {}
    tools_dir = os.path.join(out, "tools")
    for dp, dnames, fs in os.walk(tools_dir):
        dnames[:] = [d for d in dnames if d != "__pycache__"]
        for f in fs:
            if f.endswith((".pyc", ".pyo")):
                continue
            fp = os.path.join(dp, f)
            files[os.path.relpath(fp, out).replace("\\", "/")] = sha(fp)
    import yaml
    doc = {
        "_generated_by": "build/build_kit.py",
        "_note": "本 kit 是由源知识库过滤+去个人化生成的派生数据；真源不在此仓库。",
        "source_commit": commit,
        "source_dirty_tools": dirty,
        "built_at": time.strftime("%Y-%m-%dT%H:%M:%S"),
        "note": ("生成物请勿手改；改真源后重跑 build_kit.py。"
                 + ("" if not dirty else
                    " ⚠️ 本次生成时真源 tools/ 有未提交改动（见 source_dirty_tools），"
                    "仅 checkout source_commit 重建不出同一份 kit。")),
        "tools": sorted(files.keys()),
        "tool_sha256": files,
    }
    _write(os.path.join(out, "kit.yaml"),
           yaml.safe_dump(doc, allow_unicode=True, sort_keys=False))
    return commit


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default=os.environ.get("MATSCI_KB_SRC"),
                    help="源知识库根（真源）。不给则读环境变量 MATSCI_KB_SRC；"
                         "两者都没有就中止——本脚本不内置任何本机路径。")
    ap.add_argument("--out", default=KIT_ROOT, help="kit 仓库根（输出）")
    ap.add_argument("--check", action="store_true", help="只跑泄漏扫描，不生成")
    ap.add_argument("--strict", action="store_true", help="scrub 未命中即失败")
    args = ap.parse_args()

    out = os.path.abspath(args.out)
    warn = []

    def log(m):
        print(m, flush=True)

    # 私有规则缺失时**不静默降级**：少一条 scrub 就等于少一处去个人化，
    # 而少一条 denylist 等于泄漏扫描失去兜底。宁可停，也不要产出一份看似成功的脏 kit。
    # --check 例外（clone 下来的仓库本来就没有 private/），但必须把降级说出口。
    missing = private_paths()
    if missing:
        if not args.check:
            log("[ABORT] 缺少私有去个人化规则（该目录 gitignored，不随仓库发布）：")
            for m in missing:
                log(f"        build/{m}")
            log("        参照 build/rules/examples/ 在 build/rules/private/ 下补齐后重跑"
                "（说明见 build/rules/README.md）。")
            return 2
        log(f"[warn] 私有规则缺失 {len(missing)} 个（build/rules/private/ 不随仓库发布）；"
            f"本次 --check 只按通用规则扫描，源库专名不在拦截范围内。")

    if args.src:
        src = os.path.abspath(args.src)
        # 不变量 1：输出不得落在源库内（跨盘时 commonpath 抛 ValueError，
        # 而那本身就意味着 out 不在 src 里，跳过即可）
        try:
            inside = os.path.commonpath([src, out]) == src
        except ValueError:
            inside = False
        if inside:
            log(f"[ABORT] --out({out}) 落在 --src({src}) 内；拒绝生成（不变量 1）")
            return 2
    else:
        src = None

    if not args.check:
        if not src:
            log("[ABORT] 未指定源库：给 --src <库根> 或设 MATSCI_KB_SRC 环境变量")
            return 2
        if not os.path.isfile(os.path.join(src, "tools", "kb_lib.py")):
            log(f"[ABORT] 源库不像知识库（缺 tools/kb_lib.py）：{src}")
            return 2
        log(f"源库: {src}")
        log(f"输出: {out}")
        scrub = load_scrub()
        gscrub = load_global_scrub()
        sscrub = load_skill_scrub()
        drops = load_drop_sections()
        gcount = {}
        generate_tools(src, out, scrub, gscrub, gcount, warn, log)
        generate_carriers(src, out, gscrub, gcount, sscrub, drops, warn, log)
        commit = write_kit_yaml(out, src, 0)
        log(f"[kit.yaml] source_commit={commit}")
        log(f"[scrub]    全局专名替换 {sum(gcount.values())} 处"
            f"（{len(gcount)}/{len(gscrub)} 条规则命中）")

    # 不变量 2：fail-closed 泄漏扫描
    hits = scan_leaks(out)
    log("")
    if hits:
        log(f"=== 泄漏扫描：{len(hits)} 处命中 → 构建失败 ===")
        for f, i, pat, txt in hits:
            log(f"  {f}:{i}  [{pat}]  {txt}")
    else:
        log("=== 泄漏扫描：0 命中 ===")

    if warn:
        log(f"\n告警 {len(warn)} 条：")
        for w in warn:
            log(f"  ! {w}")

    if hits or (args.strict and warn):
        return 1
    return 0


